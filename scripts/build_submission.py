#
# If the real API turns out to differ, the fix is here and in
# ``StateExtractor``; nothing above this line needs to change.

class SuperPacPlayer:
    """The submission.  Instantiate once per match; it keeps its own memory."""

    name = "SUPERPAC"

    def __init__(self, player_id: int = 0, *args, **kwargs) -> None:
        self.player_id = player_id
        self.extractor = StateExtractor()
        self.brain = SuperPac(weights=WEIGHTS)
        self._started = False
        self._last_action = STAY

    # -- the many names a host might call ------------------------------
    def get_move(self, state=None, extra=None):
        return self._decide(state, extra)

    def choose_action(self, state=None, extra=None):
        return self._decide(state, extra)

    def move(self, state=None, extra=None):
        return self._decide(state, extra)

    def next_move(self, state=None, extra=None):
        return self._decide(state, extra)

    def act(self, state=None, extra=None):
        # A native GameState (our own simulator) skips the adapter entirely.
        if isinstance(state, GameState):
            return self.brain.act(state)
        return self._decide(state, extra)

    def play(self, state=None, extra=None):
        return self._decide(state, extra)

    def __call__(self, state=None, extra=None):
        return self._decide(state, extra)

    def reset(self, state=None, player_id: int = 0):
        self.player_id = player_id
        self._started = False
        if isinstance(state, GameState):
            self.brain.reset(state, player_id)

    # ------------------------------------------------------------------
    def _decide(self, raw, extra=None):
        """Translate, think, translate back - and never let go of the turn."""
        try:
            state = self.extractor.extract(raw, extra)
            if not self._started:
                self.brain.reset(state, state.me)
                self._started = True
            action = self.brain.act(state)
            self._last_action = action
            return self.extractor.encode_action(action)
        except Exception:
            # The host is owed a move even when everything above has failed.
            return self.extractor.encode_action(self._panic(raw, extra))

    def _panic(self, raw, extra):
        try:
            state = self.extractor.extract(raw, extra)
            return self.brain.fallback(state)
        except Exception:
            return self._last_action if self._last_action != STAY else EAST


