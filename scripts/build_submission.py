"""Bundle the runtime into one self-contained tournament file.

Many school tournaments accept exactly one ``.py`` file, so the package is
flattened here rather than maintained twice.  Development code - the
simulator, the bot population, the optimiser, the benchmarks - is deliberately
left out: it is dead weight in a submission and every line of it is another
line that could fail at the wrong moment.

The bundler concatenates runtime modules in dependency order, strips the
intra-package imports (everything ends up in one namespace), hoists and
de-duplicates the standard-library imports, and appends the tuned weights plus
a generous set of entry points.
"""
