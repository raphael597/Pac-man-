def strip_module(path: str):
    """Return ``(body, stdlib_import_lines)`` for one module.

    Uses the AST rather than line regexes: several modules wrap their imports
    across multiple lines, and a regex that matches only the first line leaves
    a dangling continuation behind.  ``lineno``/``end_lineno`` give the exact
    span to cut regardless of formatting.
    """
    with open(os.path.join(ROOT, path)) as fh:
        source = fh.read()
    lines = source.splitlines()
    tree = ast.parse(source)

    drop = set()
    imports = []
    for node in tree.body:
        if isinstance(node, (ast.Import, ast.ImportFrom)):
            for lineno in range(node.lineno, (node.end_lineno or node.lineno) + 1):
                drop.add(lineno)
            module = getattr(node, "module", None) or ""
            level = getattr(node, "level", 0)
            if level > 0 or module.startswith("superpac"):
                continue  # intra-package: everything shares one namespace now
            if module == "__future__":
                continue  # hoisted once into the header
            if isinstance(node, ast.Import):
                for alias in node.names:
                    text = f"import {alias.name}"
                    if alias.asname:
                        text += f" as {alias.asname}"
                    imports.append(text)
            else:
                names = ", ".join(
                    a.name + (f" as {a.asname}" if a.asname else "")
                    for a in node.names)
                imports.append(f"from {module} import {names}")
        elif isinstance(node, ast.Assign):
            targets = [t.id for t in node.targets if isinstance(t, ast.Name)]
            if targets == ["__all__"]:
                for lineno in range(node.lineno, (node.end_lineno or node.lineno) + 1):
                    drop.add(lineno)

    # A relative import nested inside a function survives the flattening and
    # then explodes at run time with "no known parent package".  Catch it here
    # instead of in the tournament.
    for node in ast.walk(tree):
        if isinstance(node, ast.ImportFrom) and node.lineno not in drop:
            module = node.module or ""
            if node.level > 0 or module.startswith("superpac"):
                raise SystemExit(
                    f"{path}:{node.lineno}: intra-package import nested inside a "
                    f"function; hoist it to module level so the bundle can flatten it")

    body = "\n".join(line for i, line in enumerate(lines, 1) if i not in drop)
    return body.strip("\n"), imports


