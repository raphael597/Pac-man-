def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--weights", default="results/weights_champion.json")
    ap.add_argument("--out", default="submission/superpac.py")
    args = ap.parse_args()

    weights_path = os.path.join(ROOT, args.weights)
    if os.path.exists(weights_path):
        with open(weights_path) as fh:
            payload = json.load(fh)
        weights_dict = payload["weights"]
        source = f"tuned ({args.weights})"
    else:
        from superpac.ai.evaluator import Weights
        weights_dict = Weights().to_dict()
        source = "hand-set defaults (no tuned file found)"

    bodies = []
    all_imports = []
    for path in RUNTIME_MODULES:
        body, imports = strip_module(path)
        all_imports.extend(imports)
        bodies.append(f"# {'=' * 74}\n# {path}\n# {'=' * 74}\n\n{body}")

    all_imports.extend(["import sys", "import types"])
    seen = set()
    ordered_imports = []
    for line in all_imports:
        if line not in seen:
            seen.add(line)
            ordered_imports.append(line)
    ordered_imports.sort(key=lambda l: (not l.startswith("import "), l))

    formatted = json.dumps(weights_dict, indent=4).replace("true", "True").replace("false", "False")
    text = (
        HEADER.format(built=time.strftime("%Y-%m-%d"),
                      weights_source=source,
                      imports="\n".join(ordered_imports))
        + "\n\n".join(bodies)
        + SELFTEST
        + FOOTER.format(weights_dict=formatted)
    )

    out_path = os.path.join(ROOT, args.out)
    os.makedirs(os.path.dirname(out_path), exist_ok=True)
    with open(out_path, "w") as fh:
        fh.write(text)

    ast.parse(text)  # fail loudly here rather than in the tournament
    lines = text.count("\n") + 1
    print(f"wrote {args.out}: {lines} lines, {len(text) / 1024:.0f} KB")
    print(f"weights: {source}")


if __name__ == "__main__":
    main()
