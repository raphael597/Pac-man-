"""SUPERPAC - adaptive multi-agent competitive game AI.

Single-file tournament build.  Generated by scripts/build_submission.py from
the superpac/ package; edit the package, not this file.

What it does, per turn:

    observe every rival's move
      -> update one independent behavioural model per rival
      -> mix competing hypotheses about each rival's policy by how well they
         have actually predicted it
      -> forecast probable rival positions several turns ahead
      -> build territory, threat and food-potential maps
      -> pick a strategy for the current situation
      -> search our own move sequences under a time budget
      -> choose the move that stays good even when the prediction is wrong

Guarantees: always returns a legal action, never raises out of ``act``, and
respects the per-move time limit via an anytime search with a safety margin.

Built: 2026-08-27
Weights: tuned (results/weights_champion.json)
"""

